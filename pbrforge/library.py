"""Library 2.0 metadata: tags, favourites, notes and physical calibration.

The material folder is the product; this sidecar is the librarian.  It is kept
separate from ``material.json`` (which is generated by the pipeline and must
remain reproducible) so a user annotation never changes a material's provenance
or pipeline hash.

Fields are deliberately small and portable:

    tags          up to 24 short labels, lower-case, no markup
    favorite      boolean
    note          one free-text note, bounded
    size_mm       [width, height] real-world size, optional
    texel_density px per millimetre, derived when size_mm is present
    created/updated ISO timestamps
"""

from __future__ import annotations

import json
import re
import time
from pathlib import Path
from typing import Any, Iterable

from .core.errors import PbrForgeError

META = "meta.json"
MAX_TAGS = 24
MAX_TAG = 32
MAX_NOTE = 2000
_TAG_RE = re.compile(r"[a-z0-9][a-z0-9 _+./-]{0,31}\Z")


def _now() -> str:
    return time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())


def clean_tags(values: Iterable[Any]) -> list[str]:
    out: list[str] = []
    for raw in values:
        tag = re.sub(r"\s+", " ", str(raw or "").strip().lower())
        if not tag or not _TAG_RE.fullmatch(tag):
            continue
        if tag not in out:
            out.append(tag[:MAX_TAG])
        if len(out) >= MAX_TAGS:
            break
    return out


def read(folder: Path) -> dict[str, Any]:
    path = Path(folder) / META
    if not path.is_file():
        return {}
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    return payload if isinstance(payload, dict) else {}


def write(folder: Path, payload: dict[str, Any]) -> Path:
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / META
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n",
                   encoding="utf-8", newline="\n")
    tmp.replace(path)
    return path


def update(folder: Path, patch: dict[str, Any]) -> dict[str, Any]:
    folder = Path(folder)
    if not folder.is_dir():
        raise PbrForgeError(f"no material folder {folder}")
    current = read(folder)
    if not current:
        current = {"created": _now()}
    if "tags" in patch:
        current["tags"] = clean_tags(patch.get("tags") or [])
    if "favorite" in patch:
        current["favorite"] = bool(patch.get("favorite"))
    if "note" in patch:
        current["note"] = str(patch.get("note") or "")[:MAX_NOTE]
    if "size_mm" in patch:
        raw = patch.get("size_mm")
        current.pop("texel_density", None)
        if raw in (None, "", []):
            current.pop("size_mm", None)
        else:
            try:
                width, height = float(raw[0]), float(raw[1])
            except (TypeError, ValueError, IndexError):
                raise PbrForgeError("size_mm must be [width_mm, height_mm]")
            if width <= 0 or height <= 0:
                raise PbrForgeError("size_mm values must be positive")
            current["size_mm"] = [round(width, 3), round(height, 3)]
    if "resolution_px" in patch:
        try:
            resolution = float(patch.get("resolution_px") or 0)
        except (TypeError, ValueError):
            resolution = 0
        if resolution > 0:
            current["resolution_px"] = round(resolution, 3)
        else:
            current.pop("resolution_px", None)
    current["updated"] = _now()
    # Texel density is derived, never accepted from the client: a stale number
    # would be worse than no number.
    current.pop("texel_density", None)
    if current.get("size_mm") and current.get("resolution_px"):
        try:
            px = float(current["resolution_px"])
            mm = float(current["size_mm"][0])
            if px > 0 and mm > 0:
                current["texel_density"] = round(px / mm, 4)
        except (TypeError, ValueError, IndexError):
            pass
    write(folder, current)
    return current


def merge(item: dict[str, Any], folder: Path) -> dict[str, Any]:
    meta = read(folder)
    out = dict(item)
    out["tags"] = list(meta.get("tags") or [])
    out["favorite"] = bool(meta.get("favorite"))
    out["note"] = str(meta.get("note") or "")
    if meta.get("size_mm"):
        out["size_mm"] = meta.get("size_mm")
    if meta.get("resolution_px"):
        out["resolution_px"] = meta.get("resolution_px")
    if meta.get("texel_density"):
        out["texel_density"] = meta.get("texel_density")
    out["meta_updated"] = meta.get("updated")
    return out


def filter_items(items: list[dict[str, Any]], *, query: str = "",
                 tag: str = "", favorite: bool | None = None,
                 category: str = "") -> list[dict[str, Any]]:
    text = (query or "").strip().lower()
    tag = (tag or "").strip().lower()
    category = (category or "").strip().lower()
    out = []
    for item in items:
        if favorite is not None and bool(item.get("favorite")) != favorite:
            continue
        if tag and tag not in [str(t).lower() for t in item.get("tags") or []]:
            continue
        if category and category not in str(item.get("category") or "").lower():
            continue
        if text:
            haystack = " ".join(str(item.get(key) or "") for key in
                                 ("name", "slug", "preset", "note", "category")).lower()
            haystack += " " + " ".join(str(t) for t in item.get("tags") or []).lower()
            if text not in haystack:
                continue
        out.append(item)
    return out


def all_tags(items: Iterable[dict[str, Any]]) -> list[str]:
    tags: set[str] = set()
    for item in items:
        tags.update(str(tag) for tag in item.get("tags") or [])
    return sorted(tags)
