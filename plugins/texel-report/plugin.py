"""Example PBRForge plugin: a map inventory and texel-density report.

Run it with:

    pbrforge plugin run texel-report <library-material> --out report

The report is read-only and does not touch the material.  It demonstrates the
supported context API: read the generated manifest, inspect the previews, and
write JSON/text into the output folder.
"""

import json


def run(ctx):
    material = {}
    try:
        material = ctx.read_json("material.json")
    except Exception:
        ctx.log("material.json was not present; reporting the folder only")
    meta = {}
    try:
        meta = ctx.read_json("meta.json")
    except Exception:
        pass

    maps = []
    folders = [("previews", ctx.material / "previews"),
               ("maps", ctx.material / "maps"),
               ("masters", ctx.material / "masters"),
               ("", ctx.material)]
    chosen = next(((label, folder) for label, folder in folders
                   if folder.is_dir() and any(folder.glob("*.png"))), None)
    if chosen is not None:
        label, folder = chosen
        for path in sorted(folder.glob("*.png")):
            relative = f"{label}/{path.name}" if label else path.name
            image = ctx.load_png(relative)
            maps.append({
                "kind": path.stem,
                "path": relative,
                "width": image.width,
                "height": image.height,
                "channels": image.channels,
                "bit_depth": image.bit_depth,
            })

    edge = None
    resolutions = material.get("resolutions") or []
    if resolutions:
        edge = resolutions[-1]
    if not edge and maps:
        edge = max(item["width"] for item in maps)
    size_mm = meta.get("size_mm")
    texel_density = None
    if edge and size_mm and len(size_mm) == 2 and size_mm[0]:
        texel_density = round(float(edge) / float(size_mm[0]), 3)

    report = {
        "material": material.get("material") or ctx.material.name,
        "pipeline_version": material.get("version"),
        "edge_px": edge,
        "size_mm": size_mm,
        "texel_density_px_per_mm": texel_density,
        "maps": maps,
        "tags": meta.get("tags") or [],
        "note": "generated by the example texel-report plugin",
    }
    ctx.write_json("texel-report.json", report)
    lines = [f"material: {report['material']}",
             f"edge: {edge or '?'} px",
             f"texel density: {texel_density or 'not calibrated'} px/mm",
             "maps:"]
    lines += [f"  {m['kind']:<12} {m['width']}x{m['height']} {m['channels']}ch {m['bit_depth']}-bit"
              for m in maps]
    ctx.write_text("texel-report.txt", "\n".join(lines) + "\n")
    return {"maps": len(maps), "texel_density": texel_density}
